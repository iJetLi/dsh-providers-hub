/**
 * 代理 URL 的**脱敏**（全仓唯一一份）。
 *
 * ## 为什么单独一个中立模块
 *
 * 它的两个消费侧在依赖图上**方向相反**：
 *
 * - `src/opencode.ts`（provider 实现）—— 造 `NormalizedProxy.label` 时用；
 * - `src/account-pool.ts`（底层池）—— 写「代理已更新」日志时用。
 *
 * 池**不能** import provider 实现（那会让底层依赖上层，并可能成环），
 * 而复制一份到池里就正是本仓库的红线「**同一语义两套判据**」
 * （2026-10-25 审计 A2-02 实测：四家 `set*Proxy` 都明文打印代理口令，
 * 而 `opencode.ts` 里**早就**有脱敏实现 —— 池拿不到它，于是各打各的）。
 *
 * ⇒ 判据住在这个**双方都能依赖**的中立文件里，两侧都只 import 它。
 *
 * ## ⚠️ 只做一件事：把 userinfo 里的口令换成 `***`
 *
 * 保留 scheme、用户名、host、port（排查时全靠这些信息），只吃掉 `:` 与 `@`
 * 之间的口令。**不做** `new URL()` 解析：那个 API 会把显式默认端口抹掉
 * （`new URL('https://h:443').port === ''`），也会对非法输入整体抛错 ——
 * 而本函数的调用点常在**错误路径**上（要展示「你填的这个地址有问题」），
 * 那里更不能因为「地址本身不合法」而再抛一次。
 */
export function maskProxyPassword(url: string): string {
  /**
   * ⚠️ **不能锚定 `^`**（2026-10-31 加固）：本函数现在也被**错误文案**调用
   *（`qoder-adapter.ts` 的 `transportErrorDetail`，issue IKR5ZD —— 传输失败的
   * message 里可能裹着一条完整代理地址）。锚定版本对「地址夹在句子中间」的情形
   * **静默漏脱敏**，而那正是最危险的方向（口令泄漏比少显示信息严重得多）。
   *
   * ⚠️⚠️ **字符类必须保持宽口径**（`[^:@/]` / `[^@/]`），**不要**为了「看起来
   * 更像 URL」去排除空白。2026-10-31 审计实测的**安全回退**：写成
   * `[^:@/\s]+` / `[^@/\s]*` 时，`http://a b:s3cr3t@h:1` 这种**带空白的脏值**
   * 会原样输出明文，而旧版（锚定 + 宽口径）本来能脱敏。脏值恰恰最需要脱敏：
   * `account-pool.ts` 的 `proxyLogText` 明写它接收「备份文件原样透传的脏值」，
   * 而日志正是用户贴进 issue 的东西。⇒ **宁可多遮，不可漏遮**。
   */
  return url.replace(/(\w+:\/\/[^:@/]+):[^@/]*@/g, '$1:***@')
}
